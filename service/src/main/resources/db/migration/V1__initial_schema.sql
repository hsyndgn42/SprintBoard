CREATE TABLE roadmap_item (
  id VARCHAR(80) PRIMARY KEY,
  title VARCHAR(180) NOT NULL,
  description CLOB NOT NULL,
  status VARCHAR(20) NOT NULL,
  target_date DATE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE member (
  id VARCHAR(100) PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  title VARCHAR(160) NOT NULL,
  role VARCHAR(40) NOT NULL,
  team_role VARCHAR(40) NOT NULL,
  engagement VARCHAR(20) NOT NULL,
  active BOOLEAN NOT NULL,
  joined_on DATE,
  left_on DATE
);
CREATE TABLE sprint (
  id VARCHAR(100) PRIMARY KEY,
  number INTEGER NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  goal CLOB NOT NULL,
  start_date DATE,
  end_date DATE,
  status VARCHAR(20) NOT NULL,
  story_points_available BOOLEAN NOT NULL
);
CREATE TABLE backlog_item (
  id VARCHAR(100) PRIMARY KEY,
  roadmap_id VARCHAR(80) REFERENCES roadmap_item(id),
  title VARCHAR(300) NOT NULL,
  criteria CLOB NOT NULL,
  work_kind VARCHAR(40) NOT NULL,
  type VARCHAR(40) NOT NULL,
  state VARCHAR(30) NOT NULL,
  estimated_hours DOUBLE PRECISION NOT NULL DEFAULT 0,
  story_points DOUBLE PRECISION,
  external_id VARCHAR(100) NOT NULL DEFAULT '',
  repeat_of_id VARCHAR(100) REFERENCES backlog_item(id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_backlog_roadmap ON backlog_item(roadmap_id);
CREATE TABLE sprint_task (
  id VARCHAR(100) PRIMARY KEY,
  sprint_id VARCHAR(100) NOT NULL REFERENCES sprint(id),
  backlog_id VARCHAR(100) NOT NULL UNIQUE REFERENCES backlog_item(id),
  title VARCHAR(300) NOT NULL,
  criteria CLOB NOT NULL,
  type VARCHAR(40) NOT NULL,
  work_kind VARCHAR(40) NOT NULL,
  status VARCHAR(20) NOT NULL,
  estimated_hours DOUBLE PRECISION NOT NULL DEFAULT 0,
  remaining_hours DOUBLE PRECISION NOT NULL DEFAULT 0,
  story_points DOUBLE PRECISION,
  external_id VARCHAR(100) NOT NULL DEFAULT ''
);
CREATE INDEX idx_task_sprint ON sprint_task(sprint_id);
CREATE TABLE assignment (
  id VARCHAR(140) PRIMARY KEY,
  task_id VARCHAR(100) NOT NULL REFERENCES sprint_task(id),
  member_id VARCHAR(100) REFERENCES member(id),
  estimated_hours DOUBLE PRECISION NOT NULL DEFAULT 0
);
CREATE TABLE leave_record (
  id VARCHAR(150) PRIMARY KEY,
  member_id VARCHAR(100) NOT NULL REFERENCES member(id),
  sprint_id VARCHAR(100) REFERENCES sprint(id),
  days DOUBLE PRECISION NOT NULL,
  precision_label VARCHAR(30) NOT NULL,
  status VARCHAR(20) NOT NULL
);
CREATE TABLE overtime_snapshot (
  id VARCHAR(150) PRIMARY KEY,
  member_id VARCHAR(100) NOT NULL REFERENCES member(id),
  sprint_id VARCHAR(100) NOT NULL REFERENCES sprint(id),
  earned_hours DOUBLE PRECISION NOT NULL,
  used_cumulative_hours DOUBLE PRECISION NOT NULL,
  balance_hours DOUBLE PRECISION NOT NULL
);
CREATE TABLE audit_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
  entity_type VARCHAR(30) NOT NULL,
  entity_id VARCHAR(150) NOT NULL,
  action VARCHAR(60) NOT NULL,
  detail_json CLOB NOT NULL
);
