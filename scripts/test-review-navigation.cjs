const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('../frontend/node_modules/typescript');
require.extensions['.ts']=(module,file)=>module._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,file);
const {revealReviewSection}=require('../frontend/src/app/pages/review-navigation.ts');
const calls=[];
const focus={setAttribute:(...a)=>calls.push(['focusAttr',...a]),focus:options=>calls.push(['focus',options])};
const disclosure={setAttribute:(...a)=>calls.push(['open',...a])};
const target={matches:()=>false,querySelector:selector=>selector==='details'?disclosure:focus,scrollIntoView:options=>calls.push(['scroll',options])};
const root={querySelector:selector=>{calls.push(['lookup',selector]);return target;}};
revealReviewSection(root,'review-scope');
assert.deepEqual(calls.map(c=>c[0]),['lookup','open','focusAttr','focus','scroll']);
assert.deepEqual(calls[1],['open','open','']);
assert.equal(calls.at(-1)[1].behavior,'auto','no motion requirement');
calls.length=0;revealReviewSection(root,'not-valid/#route');assert.equal(calls.length,0);
revealReviewSection({querySelector:()=>null},'review-missing');
const html=fs.readFileSync('frontend/src/app/pages/sprint-review.component.html','utf8');
assert.match(html,/\(click\)="goToSection\(section.id\)"/);
assert.doesNotMatch(html,/\[href\]=".*section.id/,'must not overwrite hash route');
const backlog=fs.readFileSync('frontend/src/app/pages/backlog.component.ts','utf8');
assert.doesNotMatch(backlog,/sprinte alındıktan sonra (değiştirilemez|düzeltilemez)/);
assert.match(backlog,/sprint başlamadan önce buradan düzeltilebilir/);
console.log('review navigation OK: open section, focus, scroll without hash mutation; backlog estimate copy matches planned sprint editing');
